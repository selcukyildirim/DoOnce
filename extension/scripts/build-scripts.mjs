// Builds the two scripts injected into web pages as self-contained IIFEs.
// page-agent.js and recorder.js are also embedded into the Rust engine so the
// CLI replays with exactly the same code as the extension.
//
//   node scripts/build-scripts.mjs          build into dist/ and the Rust assets
//   node scripts/build-scripts.mjs --check  fail if the Rust assets are stale

import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rustAssets = resolve(root, "../crates/doonce-engine/assets");
const entries = {
  "page-agent.js": "src/page-agent/index.ts",
  "recorder.js": "src/content/recorder.ts",
};
const check = process.argv.includes("--check");
let stale = false;

for (const [out, entry] of Object.entries(entries)) {
  const result = await build({
    entryPoints: [resolve(root, entry)],
    bundle: true,
    format: "iife",
    target: "chrome120",
    minify: false,
    legalComments: "none",
    write: false,
    banner: { js: "// Generated by extension/scripts/build-scripts.mjs. Do not edit." },
  });
  const code = result.outputFiles[0].text;
  const rustPath = resolve(rustAssets, out);
  if (check) {
    const current = await readFile(rustPath, "utf8").catch(() => "");
    if (current !== code) {
      console.error(`stale: ${rustPath} (run npm run build:scripts)`);
      stale = true;
    }
    continue;
  }
  for (const path of [resolve(root, "dist", out), rustPath]) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, code);
  }
  console.log(`built ${out} (${(code.length / 1024).toFixed(1)} KB)`);
}

if (stale) process.exit(1);
